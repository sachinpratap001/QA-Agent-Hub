/**
 * Local LLM QA Agent Orchestrator — Ollama Service
 * Communicates with local Ollama REST API (llama3.2) on port 11434
 */

require('dotenv').config();
const axios = require('axios');

const OLLAMA_URL = (process.env.OLLAMA_URL || 'http://127.0.0.1:11434').replace('://localhost', '://127.0.0.1');
const MODEL = process.env.OLLAMA_MODEL || 'llama3.2';

/**
 * Sends a generation prompt with system instructions to the local Ollama instance.
 *
 * @param {Object} options
 * @param {string} options.systemPrompt - System prompt defining agent role and guidelines
 * @param {string} options.userMessage - User instruction or prompt
 * @param {boolean} [options.stream=false] - Streaming flag (default false)
 * @returns {Promise<string>} - Text generated by Ollama model
 */
async function generate({ systemPrompt, userMessage, stream = false }) {
  try {
    const payload = {
      model: MODEL,
      system: systemPrompt,
      prompt: userMessage,
      stream: false
    };

    const response = await axios.post(`${OLLAMA_URL}/api/generate`, payload, {
      headers: {
        'Content-Type': 'application/json'
      },
      timeout: 180000 // 3 minutes timeout for LLM inference
    });

    if (response.data && typeof response.data.response === 'string') {
      return response.data.response;
    }

    throw new Error('Invalid response structure received from Ollama REST API.');
  } catch (error) {
    if (error.code === 'ECONNREFUSED') {
      throw new Error(`Unable to connect to Ollama at ${OLLAMA_URL}. Ensure Ollama is running (e.g., 'ollama serve').`);
    }
    if (error.response && error.response.data && error.response.data.error) {
      throw new Error(`Ollama API error: ${error.response.data.error}`);
    }
    throw new Error(`Ollama generation failed: ${error.message}`);
  }
}

/**
 * Checks the connectivity and model availability of the local Ollama instance.
 *
 * @returns {Promise<{ healthy: boolean, models?: Array, error?: string }>}
 */
async function checkHealth() {
  try {
    const response = await axios.get(`${OLLAMA_URL}/api/tags`, {
      timeout: 5000
    });

    const models = (response.data && response.data.models) || [];
    return {
      healthy: true,
      models: models.map(m => m.name || m)
    };
  } catch (error) {
    return {
      healthy: false,
      models: [],
      error: error.code === 'ECONNREFUSED'
        ? `Connection refused at ${OLLAMA_URL}. Is Ollama running?`
        : error.message
    };
  }
}

module.exports = {
  OLLAMA_URL,
  MODEL,
  generate,
  checkHealth
};
